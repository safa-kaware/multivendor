<?php

require_once "config/app.php";

requireLogin();


/*
|--------------------------------------------------------------------------
| ONLY CUSTOMERS
|--------------------------------------------------------------------------
*/

if (
    currentUserRole()
    !== "customer"
) {

    http_response_code(403);

    die(
        "Only customers can use the wishlist."
    );

}


/*
|--------------------------------------------------------------------------
| GET DATA
|--------------------------------------------------------------------------
*/

$productId =
    (int)
    (
        $_POST["product_id"]
        ?? 0
    );


$action =
    $_POST["action"]
    ?? "";


$userId =
    currentUserId();


/*
|--------------------------------------------------------------------------
| VALIDATE PRODUCT
|--------------------------------------------------------------------------
*/

if (
    $productId <= 0
) {

    redirect(
        BASE_URL
        . "search.php"
    );

}


/*
|--------------------------------------------------------------------------
| ADD TO WISHLIST
|--------------------------------------------------------------------------
*/

if (
    $action
    === "add"
) {

    addToWishlist(

        $pdo,

        $userId,

        $productId

    );

}


/*
|--------------------------------------------------------------------------
| REMOVE FROM WISHLIST
|--------------------------------------------------------------------------
*/

elseif (
    $action
    === "remove"
) {

    removeFromWishlist(

        $pdo,

        $userId,

        $productId

    );

}


/*
|--------------------------------------------------------------------------
| REDIRECT
|--------------------------------------------------------------------------
*/

$redirectUrl =
    $_SERVER[
        "HTTP_REFERER"
    ]
    ??
    (
        BASE_URL
        . "wishlist.php"
    );


redirect(
    $redirectUrl
);